"""Email-link and network recovery regression tests with intercepted provider only."""
import os
from playwright.sync_api import sync_playwright, expect
from auth_fixture import mock_provider, seed_account
BASE=os.environ.get('JKSPEAK_TEST_URL','http://127.0.0.1:8084').rstrip('/')
PASSWORD='Test-password-for-UI-only'
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox'])
    for suffix in ['#error=access_denied&error_code=otp_expired&error_description=expired','?error=access_denied&error_description=expired','#access_token=invalid&refresh_token=invalid']:
        page=browser.new_page()
        mock_provider(page)
        page.goto(BASE+'/login.html')
        expect(page.locator('#email')).to_be_enabled()
        page.goto(BASE+'/login.html'+suffix)
        expect(page.locator('#status')).to_contain_text('used or expired')
        expect(page.locator('#email')).to_be_enabled()
        assert '?' not in page.url and '#' not in page.url
        page.locator('#email').fill('learner@example.test')
        page.locator('#password').fill(PASSWORD)
        page.get_by_role('button',name='Log in',exact=True).click()
        expect(page).to_have_url(BASE+'/app.html')
        page.close()
    page=browser.new_page(viewport={'width':390,'height':844})
    state=mock_provider(page)
    page.goto(BASE+'/login.html?token_hash=valid-test-hash&type=email')
    expect(page.get_by_role('button',name='Confirm my email')).to_be_visible()
    assert state['verify']==[], 'Never consume a token before the user confirms'
    assert 'token_hash' not in page.url
    page.get_by_role('button',name='Confirm my email').click()
    expect(page).to_have_url(BASE+'/app.html')
    assert len(state['verify'])==1
    page.close()
    page=browser.new_page()
    state=mock_provider(page)
    page.goto(BASE+'/confirm-email.html?token_hash=expired-test-hash&type=email')
    page.get_by_role('button',name='Confirm my email').click()
    expect(page.locator('#status')).to_contain_text('used or expired')
    assert not state['resend']
    page.locator('.email-help summary').click()
    page.locator('#email').fill('learner@example.test')
    page.get_by_role('button',name='Send a new confirmation email').click()
    expect(page.locator('#status')).to_contain_text('accepted the request')
    assert len(state['resend'])==1
    expect(page.get_by_role('button',name='Request again in 60s')).to_be_disabled()
    page.close()
    for status,code,message in [(403,'email_address_not_authorized','Custom SMTP'),(429,'over_email_send_rate_limit','email sending limit'),(500,'unexpected_failure','check Auth logs')]:
        page=browser.new_page()
        mock_provider(page)
        page.route('**/auth/v1/resend?*',lambda route,request,status=status,code=code:route.fulfill(status=status,json={'error_code':code,'msg':'PRIVATE SMTP DETAIL MUST NOT DISPLAY'}))
        page.goto(BASE+'/confirm-email.html?mode=help')
        expect(page.locator('#email')).to_be_enabled()
        page.locator('#email').fill('learner@example.test')
        page.get_by_role('button',name='Send a new confirmation email').click()
        expect(page.locator('#status')).to_contain_text(message)
        expect(page.locator('#status')).to_contain_text(code)
        expect(page.locator('#status')).not_to_contain_text('PRIVATE SMTP')
        expect(page.get_by_role('button',name='Send a new confirmation email')).to_be_enabled()
        expect(page.locator('#email')).to_have_value('learner@example.test')
        page.close()
    page=browser.new_page()
    mock_provider(page)
    seed_account(page)
    page.goto(BASE+'/login.html#error=access_denied&error_description=expired')
    expect(page).to_have_url(BASE+'/app.html')
    page.close()
    page=browser.new_page()
    mock_provider(page)
    page.goto(BASE+'/login.html')
    expect(page.locator('#email')).to_be_enabled()
    page.route('**/auth/v1/token?*',lambda route:route.abort('failed'),times=1)
    page.locator('#email').fill('learner@example.test')
    page.locator('#password').fill(PASSWORD)
    page.get_by_role('button',name='Log in',exact=True).click()
    expect(page.locator('#status')).to_contain_text('Could not reach')
    expect(page.locator('#password')).to_have_value(PASSWORD)
    expect(page.get_by_role('button',name='Log in',exact=True)).to_be_enabled()
    page.get_by_role('button',name='Log in',exact=True).click()
    expect(page).to_have_url(BASE+'/app.html')
    page.close()
    page=browser.new_page()
    mock_provider(page)
    seed_account(page)
    page.route('**/auth/v1/user',lambda route:route.abort('failed'),times=1)
    page.goto(BASE+'/login.html')
    expect(page.locator('#status')).to_contain_text('could not restore')
    expect(page.locator('#email')).to_be_enabled()
    page.locator('#email').fill('learner@example.test')
    page.locator('#password').fill(PASSWORD)
    page.get_by_role('button',name='Log in',exact=True).click()
    expect(page).to_have_url(BASE+'/app.html')
    browser.close()
print('PASS (mock provider): expired/invalid query and hash links remain usable; cross-device explicit token confirmation; resend only on request; existing sessions; network retry without lost credentials.')
